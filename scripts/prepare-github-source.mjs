import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";

// Export files, not this checkout's unrelated hosting Git history. The reviewed
// tree can be committed normally on top of mohamedkbay/Nabda's existing main.
const root = await fs.realpath(fileURLToPath(new URL("../", import.meta.url)));
const output = path.join(root, "outputs/github-source");
const marker = path.join(output, ".nabda-source-export");
try {
  const entries = await fs.readdir(output);
  if (entries.length && !entries.includes(".nabda-source-export")) throw new Error("Refusing to replace an unrecognized source export directory.");
} catch (error) { if (error.code !== "ENOENT") throw error; }
const listed = execFileSync("git", ["ls-files", "--cached", "--others", "--exclude-standard", "-z"], { cwd: root, encoding: "utf8", maxBuffer: 8 * 1024 * 1024 }).split("\0").filter(Boolean);
const files = [...new Set(listed)].filter((name) => {
  if (/^(?:\.openai|\.git|\.netlify|\.wrangler|node_modules|deploy-build|dist|outputs|work|examples)\//.test(name)) return false;
  if (/(?:^|\/)(?:\.env[^/]*|\.dev\.vars[^/]*)$/.test(name) && !name.endsWith(".example")) return false;
  if (/\.(?:sqlite|sqlite3|db|csv|xlsx|vcf|pem|key|keystore|jks)$/i.test(name)) throw new Error(`Unexpected private-data or signing-key file in source export: ${name}`);
  return true;
}).sort();
const entries = [];
for (const name of files) {
  let resolved;
  try { resolved = await fs.realpath(path.join(root, name)); }
  catch (error) { if (error.code === "ENOENT") continue; throw error; }
  if (!resolved.startsWith(root + path.sep)) throw new Error(`Refusing source outside the project: ${name}`);
  const stat = await fs.stat(resolved);
  if (!stat.isFile()) throw new Error(`Unexpected non-file source entry: ${name}`);
  entries.push({ name, data: await fs.readFile(resolved), mode: stat.mode & 0o777 });
}
for (const required of ["LICENSE", "README.md", "package.json", "package-lock.json", "worker/cloudflare.ts", "lib/independent-auth.ts", "netlify.toml", "docs/DEPLOYMENT.md", "public/downloads/THIRD-PARTY-NOTICES.txt"]) {
  if (!entries.some((item) => item.name === required)) throw new Error(`Missing publication file: ${required}`);
}
await fs.rm(output, { recursive: true, force: true });
await fs.mkdir(output, { recursive: true });
for (const { name, data, mode } of entries) {
  const destination = path.resolve(output, name);
  if (!destination.startsWith(output + path.sep)) throw new Error(`Invalid source path: ${name}`);
  await fs.mkdir(path.dirname(destination), { recursive: true });
  await fs.writeFile(destination, data, { mode });
}
await fs.writeFile(marker, "Generated by scripts/prepare-github-source.mjs; not a Git repository.\n");
await fs.writeFile(path.join(root, "outputs/github-source-manifest.json"), JSON.stringify({ output: "outputs/github-source", file_count: entries.length, files: entries.map((item) => item.name), excluded: ["creator hosting metadata", "local credentials", "private data", "build/cache/test output", "unrelated local Git history"], publication_performed: false }, null, 2) + "\n");
console.log(`Prepared ${entries.length} source files at ${output}; no commit, push or deployment performed.`);
