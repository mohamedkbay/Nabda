/**
 * DTOs crossing the Electron IPC boundary. Keep these JSON serialisable and
 * free of credentials. Provider secrets are owned by the main process only.
 */
export type EntityId = string;

export interface DashboardSnapshot {
  customers: number;
  contacts: number;
  queuedMessages: number;
  sentToday: number;
  failedToday: number;
  connectedDevices: number;
  recentMessages: MessageSummary[];
}

export interface CustomerSummary {
  id: EntityId;
  name: string;
  phone?: string;
  notes?: string;
  createdAt: string;
}

export interface ContactSummary {
  id: EntityId;
  customerId?: EntityId;
  customerName?: string;
  name: string;
  phone: string;
  optedOut: boolean;
  createdAt: string;
}

export type DesktopMessageStatus =
  | "queued"
  | "sent"
  | "delivered"
  | "failed"
  | "expired"
  | "cancelled";

export interface MessageSummary {
  id: EntityId;
  contactName?: string;
  to: string;
  bodyPreview: string;
  status: DesktopMessageStatus;
  createdAt: string;
}

export interface DeviceSummary {
  id: EntityId;
  name: string;
  status: "connected" | "offline" | "revoked";
  lastSeenAt?: string;
  lanAddress?: string;
}

export interface DesktopSettings {
  provider: "mock" | "httpsms";
  providerEndpoint?: string;
  senderLabel?: string;
  secretConfigured: boolean;
  startWorkerOnLaunch: boolean;
}

export interface ConnectionTestResult {
  ok: boolean;
  message: string;
  checkedAt: string;
}

export interface PairingSession {
  id: EntityId;
  pairingUri: string;
  manualAddress: string;
  oneTimeCode: string;
  expiresAt: string;
  /** Optional QR generated by core. It must be an inline SVG data URL. */
  qrDataUrl?: string;
}

export interface BackupResult {
  ok: boolean;
  fileName: string;
  message: string;
}

export interface DesktopServices {
  dashboard: {
    getSnapshot(): Promise<DashboardSnapshot>;
  };
  customers: {
    list(): Promise<CustomerSummary[]>;
    create(input: { name: string; phone?: string; notes?: string }): Promise<CustomerSummary>;
  };
  contacts: {
    list(): Promise<ContactSummary[]>;
    create(input: {
      name: string;
      phone: string;
      customerId?: string;
      consentConfirmed: true;
    }): Promise<ContactSummary>;
    setOptOut(input: { id: string; optedOut: boolean }): Promise<ContactSummary>;
  };
  messages: {
    list(input: { limit: number }): Promise<MessageSummary[]>;
    enqueue(input: {
      contactId?: string;
      to: string;
      body: string;
      consentConfirmed: true;
    }): Promise<MessageSummary>;
    cancel(input: { id: string }): Promise<MessageSummary>;
  };
  devices: {
    list(): Promise<DeviceSummary[]>;
    createPairingSession(input: { ttlSeconds: 300; lanOrigin: string }): Promise<PairingSession>;
    claimPairing(input: {
      pairingCode: string;
      deviceName: string;
      installationId: string;
      appVersion: string;
      platform: "android";
      lanOrigin: string;
    }): Promise<{ deviceId: string; deviceToken: string }>;
    receiveHeartbeat(input: {
      bearerToken: string;
      installationId: string;
      appVersion: string;
      platform: "android";
    }): Promise<{ deviceId: string; acceptedAt: string }>;
    revoke(input: { id: string }): Promise<void>;
    testHeartbeat(input: { id: string }): Promise<ConnectionTestResult>;
  };
  settings: {
    get(): Promise<DesktopSettings>;
    save(input: {
      provider: "mock" | "httpsms";
      providerEndpoint?: string;
      senderLabel?: string;
      startWorkerOnLaunch: boolean;
    }): Promise<DesktopSettings>;
    /** Connection metadata only. This method must never send an SMS. */
    testProviderConnection(input: {
      provider: "mock" | "httpsms";
      secret?: string;
      endpoint?: string;
    }): Promise<ConnectionTestResult>;
  };
  backup: {
    exportTo(targetPath: string): Promise<BackupResult>;
    validateAndImportFrom(sourcePath: string): Promise<BackupResult>;
  };
}
